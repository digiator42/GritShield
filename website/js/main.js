function buildNodeMesh(cfg, radius) {
  let geo;
  switch (cfg.id) {
    case "security": geo = new THREE.IcosahedronGeometry(0.62, 0); break;
    case "macros": geo = new THREE.TetrahedronGeometry(0.7, 0); break;
    case "di": geo = new THREE.OctahedronGeometry(0.66, 0); break;
    case "routing": geo = new THREE.TorusGeometry(0.42, 0.17, 12, 24); break;
    case "admin": geo = new THREE.BoxGeometry(0.9, 0.9, 0.9); break;
    case "events": geo = new THREE.TorusKnotGeometry(0.42, 0.15, 90, 12); break;
    case "websocket": geo = new THREE.CylinderGeometry(0.34, 0.34, 0.9, 24); break;
    case "database": geo = new THREE.CylinderGeometry(0.62, 0.62, 0.55, 12); break;
    default: geo = new THREE.SphereGeometry(0.6, 24, 20);
  }
  const color = new THREE.Color(cfg.color);
  const coreMat = new THREE.MeshStandardMaterial({
    color, roughness: 0.25, metalness: 0.6, emissive: color, emissiveIntensity: 0.55,
  });
  const mesh = new THREE.Mesh(geo, coreMat);
  // wireframe shell
  const wire = new THREE.LineSegments(
    new THREE.EdgesGeometry(geo),
    new THREE.LineBasicMaterial({ color, transparent: true, opacity: 0.75 })
  );
  wire.scale.setScalar(1.32);
  mesh.add(wire);
  return mesh;
}

const nodes = [];
const nodeRadius = 7.5;
const nodeCount = MODULES.length;

// Tilted elliptical orbit rings
for (let i = 0; i < nodeCount; i++) {
  const cfg = MODULES[i];
  const angle = (i / nodeCount) * Math.PI * 2;
  const tiltX = Math.sin(i * 1.7) * 0.35;
  const tiltZ = Math.cos(i * 1.3) * 0.28;
  const x = Math.cos(angle) * nodeRadius;
  const z = Math.sin(angle) * nodeRadius * 0.82;
  const y = Math.sin(angle * 1.3) * 1.6;

  const holder = new THREE.Group();
  holder.rotation.x = -0.18 + tiltX;
  holder.rotation.z = -0.1 + tiltZ;

  const mesh = buildNodeMesh(cfg, nodeRadius);
  mesh.position.set(x, y, z);
  holder.add(mesh);

  // point light at each node
  const light = new THREE.PointLight(cfg.color, 1.4, 8);
  light.position.set(x, y, z);
  holder.add(light);

  // CSS2D label
  const labelDiv = document.createElement("div");
  labelDiv.className = "node-label";
  labelDiv.textContent = cfg.icon + "  " + cfg.name;
  labelDiv.style.borderColor = "rgba(" + (cfg.color >> 16) + "," + ((cfg.color >> 8) & 255) + "," + (cfg.color & 255) + ",0.5)";
  const label = new CSS2DObject(labelDiv);
  label.position.set(x, y + 1.35, z);
  holder.add(label);

  holder.userData = { cfg, mesh, basePos: new THREE.Vector3(x, y, z), angle, label: labelDiv };
  shieldGroup.add(holder);
  nodes.push(holder);
}

// Connected ring (lines between adjacent nodes + node->core)
{
  const pts = nodes.map((n) => n.userData.basePos);
  const ringPos = [];
  for (let i = 0; i < pts.length; i++) {
    const a = pts[i], b = pts[(i + 1) % pts.length];
    ringPos.push(a.x, a.y, a.z, b.x, b.y, b.z);
  }
  const rg = new THREE.BufferGeometry();
  rg.setAttribute("position", new THREE.BufferAttribute(new Float32Array(ringPos), 3));
  const ringMat = new THREE.LineBasicMaterial({ color: 0x1d3a63, transparent: true, opacity: 0.5 });
  shieldGroup.add(new THREE.LineSegments(rg, ringMat));

  // spokes: node -> origin
  for (const n of nodes) {
    const p = n.userData.basePos;
    const v = p.clone().normalize().multiplyScalar(2.6);
    const geo = new THREE.BufferGeometry().setFromPoints([v, p]);
    const m = new THREE.LineBasicMaterial({ color: new THREE.Color(n.userData.cfg.color).multiplyScalar(0.7), transparent: true, opacity: 0.16 });
    shieldGroup.add(new THREE.Line(geo, m));
  }
}

// Travelling energy packets along spokes
const packets = [];
{
  const geo = new THREE.SphereGeometry(0.07, 12, 12);
  for (const n of nodes) {
    const p = n.userData.basePos;
    const inner = p.clone().normalize().multiplyScalar(2.6);
    const mat = new THREE.MeshBasicMaterial({ color: n.userData.cfg.color, transparent: true, opacity: 0.95 });
    const mesh = new THREE.Mesh(geo, mat);
    shieldGroup.add(mesh);
    packets.push({ mesh, inner, outer: p.clone(), speed: 0.5 + Math.random() * 0.8, offset: Math.random() * Math.PI * 2 });
  }
}

