function makeStars() {
  const count = 3600;
  const pos = new Float32Array(count * 3);
  const col = new Float32Array(count * 3);
  for (let i = 0; i < count; i++) {
    const r = 80 + Math.random() * 220;
    const theta = Math.random() * Math.PI * 2;
    const phi = Math.acos(2 * Math.random() - 1);
    pos[i * 3] = r * Math.sin(phi) * Math.cos(theta);
    pos[i * 3 + 1] = r * Math.sin(phi) * Math.sin(theta);
    pos[i * 3 + 2] = r * Math.cos(phi);
    const tint = Math.random();
    const b = 0.55 + Math.random() * 0.45;
    col[i * 3] = tint < 0.8 ? b : 0.7 * b;        // mostly white -> slight cyan
    col[i * 3 + 1] = tint < 0.8 ? b * 0.9 : b;
    col[i * 3 + 2] = tint < 0.8 ? b : 1.0 * b;
  }
  const g = new THREE.BufferGeometry();
  g.setAttribute("position", new THREE.BufferAttribute(pos, 3));
  g.setAttribute("color", new THREE.BufferAttribute(col, 3));
  const m = new THREE.PointsMaterial({ size: 0.22, vertexColors: true, transparent: true, opacity: 0.9, depthWrite: false });
  const pts = new THREE.Points(g, m);
  pts.frustumCulled = false;
  return pts;
}
const stars = makeStars();
