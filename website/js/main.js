function hexagonPrismLines(radius, height, ySegs) {
  const points = [];
  // top & bottom hexagon rings
  function ring(y) {
    const ring = [];
    for (let i = 0; i < 6; i++) {
      const a = (i / 6) * Math.PI * 2 + Math.PI / 6;
      ring.push(new THREE.Vector3(Math.cos(a) * radius, y, Math.sin(a) * radius));
    }
    return ring;
  }
  const top = ring(height / 2);
  const bot = ring(-height / 2).map((v) => v.clone());
  const innerTop = ring(height / 2 - 0.12);
  const innerBot = ring(-height / 2 + 0.12);

  // vertical slices
  const ys = [];
  for (let i = 0; i <= ySegs; i++) ys.push(-height / 2 + (height * i) / ySegs);

  // build edges: hexagon sides top & bottom, verticals, and inner shell
  for (const [arr, colorHex] of [
    [top, 0x4fd8ff],
    [bot, 0x4fd8ff],
  ]) {
    for (let i = 0; i < 6; i++) {
      points.push(seg(arr[i], arr[(i + 1) % 6], colorHex));
    }
  }
  for (let i = 0; i < 6; i++) {
    points.push(seg(top[i], bot[i], 0x2f7fbb));
    points.push(seg(innerTop[i], innerBot[i], 0x2f7fbb));
  }
  for (let i = 0; i < 6; i++) {
    points.push(seg(top[i], innerTop[i], 0x2f7fbb));
    points.push(seg(bot[i], innerBot[i], 0x2f7fbb));
    points.push(seg(top[i], innerTop[(i + 1) % 6], 0x2f7fbb));
    points.push(seg(bot[i], innerBot[(i + 1) % 6], 0x2f7fbb));
  }
  return points;
}
function seg(a, b, colorHex) {
  const c = new THREE.Color(colorHex);
  return { a, b, color: c };
}

// Hexagon prism (wireframe edges, vertex-colored)
{
  const segs = hexagonPrismLines(2.6, 4.6, 3);
  const positions = new Float32Array(segs.length * 2 * 3);
  const colors = new Float32Array(segs.length * 2 * 3);
  segs.forEach((s, i) => {
    positions.set([s.a.x, s.a.y, s.a.z], i * 6);
    positions.set([s.b.x, s.b.y, s.b.z], i * 6 + 3);
    colors.set([s.color.r, s.color.g, s.color.b], i * 6);
    colors.set([s.color.r, s.color.g, s.color.b], i * 6 + 3);
  });
  const g = new THREE.BufferGeometry();
  g.setAttribute("position", new THREE.BufferAttribute(positions, 3));
  g.setAttribute("color", new THREE.BufferAttribute(colors, 3));
  const m = new THREE.LineBasicMaterial({ vertexColors: true, transparent: true, opacity: 0.55 });
  shieldGroup.add(new THREE.LineSegments(g, m));

  // translucent core
  const core = new THREE.CylinderGeometry(2.5, 2.5, 4.4, 6, 1);
  const coreMat = new THREE.MeshBasicMaterial({
    color: 0x0a2a44, transparent: true, opacity: 0.28, side: THREE.DoubleSide,
  });
  const coreMesh = new THREE.Mesh(core, coreMat);
  coreMesh.geometry.translate(0, 0, 0);
  coreMesh.rotation.y = Math.PI / 6;
  shieldGroup.add(coreMesh);
}

// Particle lattice filling the core
{
  const count = 2600;
  const pos = new Float32Array(count * 3);
  const col = new Float32Array(count * 3);
  const colCyan = new THREE.Color(0x53e6ff);
  const colViolet = new THREE.Color(0x8f7bff);
  const colWhite = new THREE.Color(0xdff5ff);
  for (let i = 0; i < count; i++) {
    // point in a filled hexagon cylinder
    const r = Math.cbrt(Math.random()) * 2.5;
    const a = Math.random() * Math.PI * 2;
    const y = (Math.random() * 2 - 1) * 4.2;
    pos[i * 3] = Math.cos(a) * r;
    pos[i * 3 + 1] = y;
    pos[i * 3 + 2] = Math.sin(a) * r;
    const t = Math.random();
    const c = t < 0.15 ? colWhite : t < 0.5 ? colCyan : colViolet;
    const fade = 0.55 + Math.random() * 0.45;
    col[i * 3] = c.r * fade;
    col[i * 3 + 1] = c.g * fade;
    col[i * 3 + 2] = c.b * fade;
  }
  const g = new THREE.BufferGeometry();
  g.setAttribute("position", new THREE.BufferAttribute(pos, 3));
  g.setAttribute("color", new THREE.BufferAttribute(col, 3));
  const m = new THREE.PointsMaterial({ size: 0.09, vertexColors: true, transparent: true, depthWrite: false, opacity: 0.9 });
  const p = new THREE.Points(g, m);
  shieldGroup.add(p);
}

