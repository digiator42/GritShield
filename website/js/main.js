function openPanel(idx) {
  const cfg = MODULES[idx];
  elCat.textContent = cfg.cat;
  elCat.style.color = "#" + cfg.color.toString(16).padStart(6, "0");
  elTitle.textContent = cfg.icon + " " + cfg.name;
  elTag.textContent = cfg.tagline;
  elDesc.textContent = cfg.desc;
  elFile.textContent = "// " + cfg.file;
  elCode.textContent = cfg.code.trim();
  panel.classList.add("open");
  panel.setAttribute("aria-hidden", "false");
  interacting = true;
  controls.autoRotate = false;
}
function closePanel() {
  panel.classList.remove("open");
  panel.setAttribute("aria-hidden", "true");
  interacting = false;
  controls.autoRotate = true;
}
closeBtn.addEventListener("click", closePanel);
panel.addEventListener("click", (e) => { if (e.target === panel) closePanel(); });
document.addEventListener("keydown", (e) => { if (e.key === "Escape") closePanel(); });

function setPointer(e) {
  pointer.x = (e.clientX / innerWidth) * 2 - 1;
  pointer.y = -(e.clientY / innerHeight) * 2 + 1;
}
function pick(e) {
  setPointer(e);
  raycaster.setFromCamera(pointer, camera);
  const meshes = [];
  for (const n of nodes) meshes.push(n.userData.mesh);
  const hits = raycaster.intersectObjects(meshes, false);
  return hits.length ? nodes.find((n) => n.userData.mesh === hits[0].object) : null;
}
window.addEventListener("pointermove", (e) => {
  if (interacting) return;
  const hit = pick(e);
  if (hit !== hovered) {
    if (hovered) {
      hovered.userData.mesh.scale.setScalar(1);
      hovered.userData.label.classList.remove("off");
    }
    hovered = hit;
    if (hovered) {
      hovered.userData.mesh.scale.setScalar(1.35);
      hovered.userData.label.classList.add("off");
      renderer.domElement.style.cursor = "pointer";
    } else {
      renderer.domElement.style.cursor = "";
    }
  }
});
window.addEventListener("click", (e) => {
  const hit = pick(e);
  if (hit) {
    const idx = nodes.indexOf(hit);
    openPanel(idx);
  }
});

