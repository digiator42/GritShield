/* =========================================================================
   Animation loop
   ========================================================================= */
const clock = new THREE.Clock();
function animate() {
  requestAnimationFrame(animate);
  const t = clock.getElapsedTime();

  // shield core idle motion
  shieldGroup.rotation.y = t * 0.06;
  stars.rotation.y = t * 0.004;

  // background parallax
  const camVec = camera.position.clone().normalize();
  stars.position.lerp(camVec.multiplyScalar(-2), 0.02);

  // nodes float + spin
  nodes.forEach((n, i) => {
    const cfg = n.userData;
    const m = cfg.mesh;
    m.rotation.x = t * 0.5 + i;
    m.rotation.y = t * 0.7 + i * 1.3;
    m.position.x = cfg.basePos.x + Math.sin(t * 0.8 + i * 2.1) * 0.25;
    m.position.y = cfg.basePos.y + Math.cos(t * 0.6 + i * 1.7) * 0.3;
    m.position.z = cfg.basePos.z + Math.sin(t * 0.55 + i) * 0.2;
    // label follows
    const l = n.children.find((c) => c.isCSS2DObject);
    if (l) l.position.set(m.position.x, m.position.y + 1.35, m.position.z);
  });

  // energy packets
  for (const pk of packets) {
    const k = (Math.sin(t * pk.speed + pk.offset) + 1) / 2;
    pk.mesh.position.lerpVectors(pk.inner, pk.outer, k);
    pk.mesh.material.opacity = 0.35 + 0.65 * k;
  }

  controls.update();
  composer.render();
}
animate();

